"""Create templates/test_protocol_template.docx — our own neutral template (CC BY 4.0).

Run once: python templates/build_template.py   (requires python-docx)
"""
from pathlib import Path

from docx import Document
from docx.shared import Pt

OUT = Path(__file__).resolve().parent / "test_protocol_template.docx"


def main() -> None:
    doc = Document()
    doc.styles["Normal"].font.size = Pt(10)
    doc.add_heading("Design Verification Test Protocol", level=0)
    doc.add_paragraph("Product: {{PRODUCT}}")
    doc.add_paragraph("Case: {{CASE}}    Draft run: {{RUN}}    Evidence snapshot: {{SNAPSHOT}}")
    p = doc.add_paragraph()
    p.add_run("DRAFT FOR REVIEW — generated by TraceDraft. Red text marks values that are missing, in conflict "
              "or flagged by the citation verifier. Every value carries its evidence id.").italic = True
    doc.add_heading("1 Purpose", level=1)
    doc.add_paragraph("This protocol defines the verification tests, sample sizes and acceptance criteria "
                      "for the product named above.")
    doc.add_heading("2 Test tables", level=1)
    doc.add_paragraph("{{TABLES}}")
    doc.add_heading("3 Approval", level=1)
    doc.add_paragraph("Prepared by: ________    Reviewed by: ________    Date: ________")
    doc.save(OUT)
    print(OUT)


if __name__ == "__main__":
    main()
